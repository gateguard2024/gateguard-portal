-- ============================================================
-- Migration 226 — Resident app access (Part 4 · Nexus Resident app)
-- Run on BETA first, verify, then PROD.
--
--   resident_app_access   who may use the resident app at which property. One row per
--                         person per site. The app matches the resident's verified login
--                         email to `email`. Filled by the property portal / move-in
--                         (and by hand while testing). `brivo_user_id` is checked live in
--                         Brivo on every open, so a suspended Brivo user is paused instantly.
--   resident_door_opens   audit trail: every open attempt from the app (opened / denied / error).
-- Service-role only (Nexus APIs). RLS on + service_role policy, no anon grants.
-- ============================================================

CREATE TABLE IF NOT EXISTS public.resident_app_access (
  id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  site_id        uuid NOT NULL REFERENCES public.sites(id) ON DELETE CASCADE,
  email          text NOT NULL CHECK (email = lower(email)),
  first_name     text,
  last_name      text,
  unit_number    text,
  brivo_user_id  text,            -- their Brivo user at this site (null = no Brivo check)
  clerk_user_id  text,            -- set on first app login
  active         boolean NOT NULL DEFAULT true,
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  UNIQUE (site_id, email)
);
CREATE INDEX IF NOT EXISTS resident_app_access_email ON public.resident_app_access (email) WHERE active;
CREATE INDEX IF NOT EXISTS resident_app_access_clerk ON public.resident_app_access (clerk_user_id);

CREATE TABLE IF NOT EXISTS public.resident_door_opens (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id        uuid NOT NULL REFERENCES public.sites(id) ON DELETE CASCADE,
  access_id      uuid REFERENCES public.resident_app_access(id) ON DELETE SET NULL,
  clerk_user_id  text,
  door_id        text NOT NULL,   -- Brivo access-point id
  door_name      text,
  result         text NOT NULL CHECK (result IN ('opened', 'denied', 'error')),
  detail         text,
  created_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS resident_door_opens_site_time ON public.resident_door_opens (site_id, created_at DESC);

DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['resident_app_access', 'resident_door_opens'] LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('DROP POLICY IF EXISTS "service_role_all_%s" ON public.%I', t, t);
    EXECUTE format('CREATE POLICY "service_role_all_%s" ON public.%I FOR ALL TO service_role USING (true) WITH CHECK (true)', t, t);
  END LOOP;
END $$;
