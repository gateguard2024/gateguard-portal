-- GateGuard OS — Migration 194: Tasks (Wrike/Monday-style task detail)
-- Part 1 (Dealer) · My Day → Tasks. Builds on `todos` (023, 024).
-- Run on BETA Supabase first, then prod. Safe to re-run (IF NOT EXISTS / DROP ... IF EXISTS).
--
-- Adds to todos: Waiting status (+ waiting_on), start date, task number (T-123),
--   tags, watchers, estimate, subtasks (parent_task_id), sort order; widens link types.
-- New tables: todo_checklist_items, todo_comments, todo_activity, todo_dependencies,
--   todo_links, todo_time_entries, notifications.
-- Security fix: the 023/024 policies had no role, so they applied to every role
--   (incl. anon). They are recreated as service_role only. No browser code reads these
--   tables with the anon key — all access goes through /api/todos.
--
-- Note: parent_todo_id (024) stays as the link between repeats of a recurring task.
--   Subtasks use the new parent_task_id so the two never mix.

-- ── 1. todos: new columns ────────────────────────────────────────────────────
ALTER TABLE public.todos
  ADD COLUMN IF NOT EXISTS waiting_on     text,                    -- parts | customer | task | other
  ADD COLUMN IF NOT EXISTS start_date     date,
  ADD COLUMN IF NOT EXISTS estimate_mins  integer CHECK (estimate_mins IS NULL OR estimate_mins >= 0),
  ADD COLUMN IF NOT EXISTS tags           text[] NOT NULL DEFAULT '{}',
  ADD COLUMN IF NOT EXISTS watcher_ids    text[] NOT NULL DEFAULT '{}',   -- Clerk user IDs
  ADD COLUMN IF NOT EXISTS parent_task_id uuid REFERENCES public.todos(id) ON DELETE CASCADE,
  ADD COLUMN IF NOT EXISTS sort_order     integer NOT NULL DEFAULT 0;

-- Task number for keys like T-123. Existing rows are numbered when the column is added.
ALTER TABLE public.todos
  ADD COLUMN IF NOT EXISTS task_number bigint GENERATED BY DEFAULT AS IDENTITY;
CREATE UNIQUE INDEX IF NOT EXISTS idx_todos_task_number ON public.todos(task_number);

-- ── 2. todos: status + link-type checks ─────────────────────────────────────
-- Drop the original inline CHECKs by looking them up (their names are generated).
DO $$
DECLARE c record;
BEGIN
  FOR c IN
    SELECT conname FROM pg_constraint
    WHERE conrelid = 'public.todos'::regclass AND contype = 'c'
      AND (pg_get_constraintdef(oid) ILIKE '%status%' OR pg_get_constraintdef(oid) ILIKE '%linked_type%'
           OR pg_get_constraintdef(oid) ILIKE '%waiting_on%')
      AND pg_get_constraintdef(oid) NOT ILIKE '%estimate_mins%'
  LOOP
    EXECUTE format('ALTER TABLE public.todos DROP CONSTRAINT %I', c.conname);
  END LOOP;
END $$;

ALTER TABLE public.todos
  ADD CONSTRAINT todos_status_check
    CHECK (status IN ('open', 'in_progress', 'waiting', 'done')),
  ADD CONSTRAINT todos_waiting_on_check
    CHECK (waiting_on IS NULL OR waiting_on IN ('parts', 'customer', 'task', 'other')),
  -- 'property' (= sites) and 'dealer' (= organizations) are what the record search and the
  -- old /todos page already send; the 023 CHECK rejected them, so those saves failed.
  ADD CONSTRAINT todos_linked_type_check
    CHECK (linked_type IS NULL OR linked_type IN ('work_order', 'site', 'property', 'lead', 'opportunity', 'customer', 'dealer'));

-- ── 3. todos: indexes for the Tasks screen filters ──────────────────────────
CREATE INDEX IF NOT EXISTS idx_todos_parent_task  ON public.todos(parent_task_id);
CREATE INDEX IF NOT EXISTS idx_todos_assigned_to  ON public.todos(assigned_to);
CREATE INDEX IF NOT EXISTS idx_todos_created_by   ON public.todos(created_by);
CREATE INDEX IF NOT EXISTS idx_todos_org_status   ON public.todos(org_id, status);
CREATE INDEX IF NOT EXISTS idx_todos_due_date     ON public.todos(due_date);
CREATE INDEX IF NOT EXISTS idx_todos_linked       ON public.todos(linked_type, linked_id);
CREATE INDEX IF NOT EXISTS idx_todos_watchers     ON public.todos USING gin (watcher_ids);

-- ── 4. Checklist ─────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.todo_checklist_items (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  todo_id     uuid NOT NULL REFERENCES public.todos(id) ON DELETE CASCADE,
  title       text NOT NULL,
  done        boolean NOT NULL DEFAULT false,
  done_at     timestamptz,
  done_by     text,                                   -- Clerk user ID
  sort_order  integer NOT NULL DEFAULT 0,
  created_at  timestamptz NOT NULL DEFAULT now()
);
-- Grant Data API access (required — Supabase enforces this Oct 30 2026)
GRANT ALL ON TABLE public.todo_checklist_items TO postgres, anon, authenticated, service_role;
ALTER TABLE public.todo_checklist_items ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "service_role_all_todo_checklist_items" ON public.todo_checklist_items;
CREATE POLICY "service_role_all_todo_checklist_items"
  ON public.todo_checklist_items FOR ALL TO service_role USING (true) WITH CHECK (true);
CREATE INDEX IF NOT EXISTS idx_todo_checklist_todo ON public.todo_checklist_items(todo_id, sort_order);

