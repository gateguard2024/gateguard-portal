-- ============================================================
-- Migration 195 — Sales board (Part 1 · Dealer)
-- Run on BETA first, verify, then prod. Safe to run more than once.
--
-- Adds to opportunities:
--   deal_number        D-1042 style key (identity, unique)
--   stage_changed_at   when the deal entered its current stage (days-in-stage,
--                      15-day "stalled" warning). Kept current by a trigger so
--                      every screen that changes stage keeps it right.
--   lost_competitor / lost_note   detail captured on the "Mark lost" dialog
--   archived_at        "Archive" drop zone — hides a deal without calling it lost
--   tags               free tags
--   incumbent_vendor / incumbent_contract_end   current vendor + when they're up
--   quote_total / quote_status   (from 180 — missing on beta, added if absent)
--
-- Data clean-up:
--   "dead" deals become "lost" (Dead is merged into Lost).
--
-- No new tables, so no GRANT block is needed.
-- "Why did this deal move?" notes are stored in crm_activities (type = 'stage_change').
-- ============================================================

ALTER TABLE public.opportunities
  ADD COLUMN IF NOT EXISTS deal_number            bigint GENERATED BY DEFAULT AS IDENTITY,
  ADD COLUMN IF NOT EXISTS stage_changed_at       timestamptz,
  ADD COLUMN IF NOT EXISTS lost_competitor        text,
  ADD COLUMN IF NOT EXISTS lost_note              text,
  ADD COLUMN IF NOT EXISTS archived_at            timestamptz,
  ADD COLUMN IF NOT EXISTS tags                   text[] NOT NULL DEFAULT '{}',
  ADD COLUMN IF NOT EXISTS incumbent_vendor       text,
  ADD COLUMN IF NOT EXISTS incumbent_contract_end date,
  ADD COLUMN IF NOT EXISTS quote_total            numeric,
  ADD COLUMN IF NOT EXISTS quote_status           text;

-- Start new deal numbers at 1001 so keys look like D-1001, D-1002 …
-- Existing rows were numbered 1, 2, 3 … by the identity default; renumber them
-- once (oldest first) into the 1001+ range, then move the sequence past them.
DO $$
DECLARE seq text := pg_get_serial_sequence('public.opportunities', 'deal_number');
BEGIN
  IF EXISTS (SELECT 1 FROM public.opportunities WHERE deal_number < 1001) THEN
    WITH ordered AS (
      SELECT id, 1000 + row_number() OVER (ORDER BY created_at NULLS FIRST, id) AS n
      FROM public.opportunities
    )
    UPDATE public.opportunities o SET deal_number = ordered.n + 100000   -- step 1: park out of range (avoids unique clashes)
    FROM ordered WHERE o.id = ordered.id;
    UPDATE public.opportunities SET deal_number = deal_number - 100000;  -- step 2: final 1001+
  END IF;
  PERFORM setval(seq, GREATEST((SELECT COALESCE(MAX(deal_number), 1000) FROM public.opportunities), 1000));
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS opportunities_deal_number_key ON public.opportunities (deal_number);

-- Days-in-stage starting point for existing deals: last update (best we know).
UPDATE public.opportunities
   SET stage_changed_at = COALESCE(updated_at, created_at, now())
 WHERE stage_changed_at IS NULL;

ALTER TABLE public.opportunities ALTER COLUMN stage_changed_at SET DEFAULT now();

-- Keep stage_changed_at right no matter which screen changes the stage.
CREATE OR REPLACE FUNCTION public.opportunities_stage_changed()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.stage IS DISTINCT FROM OLD.stage THEN
    NEW.stage_changed_at := now();
  END IF;
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_opportunities_stage_changed ON public.opportunities;
CREATE TRIGGER trg_opportunities_stage_changed
  BEFORE UPDATE OF stage ON public.opportunities
  FOR EACH ROW EXECUTE FUNCTION public.opportunities_stage_changed();

-- Dead → Lost (Dead is merged into Lost).
UPDATE public.opportunities
   SET stage       = 'lost',
       lost_at     = COALESCE(lost_at, updated_at, now()),
       lost_reason = COALESCE(NULLIF(lost_reason, ''), 'Other')
 WHERE stage IN ('dead', 'archived', 'closed_lost');

-- Board + Won/Lost tab lookups.
CREATE INDEX IF NOT EXISTS idx_opportunities_stage_open
  ON public.opportunities (stage) WHERE deleted_at IS NULL AND archived_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_opportunities_won_at  ON public.opportunities (won_at)  WHERE won_at  IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_opportunities_lost_at ON public.opportunities (lost_at) WHERE lost_at IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_crm_activities_opp_due
  ON public.crm_activities (opportunity_id, due_at) WHERE completed_at IS NULL;
