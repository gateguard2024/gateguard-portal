-- 193_controller_schema.sql
-- GateGuard gate/door controller tables (ESP32 controllers talk to the door-api edge function,
-- which uses the service_role key; nothing on the device ever holds a Supabase key).
--
-- Hardened per project rules:
--   * explicit GRANT block after every CREATE TABLE (+ sequence grant for identity/serial ids)
--   * RLS enabled on every table, service_role-only policies
--   * credentials and commands are never readable/writable by anon or authenticated
-- Run on BETA first, verify, then PROD.

begin;

-- =========================================================================
-- doors: one row per controller
-- =========================================================================
create table if not exists public.doors (
  id               text primary key,               -- matches DOOR_ID in the firmware
  name             text,
  device_key_hash  text not null,                  -- sha256 hex of DEVICE_KEY (never the key itself)
  mode             text not null default 'normal' check (mode in ('normal','unlocked','lockdown')),
  card_version     bigint not null default 1,      -- bumps whenever this door's cards change
  last_seen        timestamptz,
  fw_version       text,
  created_at       timestamptz not null default now()
);
grant all on table public.doors to postgres, anon, authenticated, service_role;

-- =========================================================================
-- door_credentials: cards allowed at each door (SENSITIVE)
-- =========================================================================
create table if not exists public.door_credentials (
  id           uuid primary key default gen_random_uuid(),
  door_id      text not null references public.doors(id) on delete cascade,
  credential   text not null,                      -- '26-45-12345' = bits-facility-card
  person_name  text,
  valid_until  timestamptz,                        -- null = no end date
  active       boolean not null default true,
  created_at   timestamptz not null default now(),
  unique (door_id, credential)
);
grant all on table public.door_credentials to postgres, anon, authenticated, service_role;

-- =========================================================================
-- door_events: everything the controllers report
-- =========================================================================
create table if not exists public.door_events (
  id           bigint generated by default as identity primary key,
  door_id      text not null references public.doors(id) on delete cascade,
  type         text not null,                      -- granted, denied, rex, remote_unlock, power_cycle_start, ...
  credential   text,
  device_ts    timestamptz,                        -- controller clock (null if it had no time yet)
  received_at  timestamptz not null default now()
);
grant all on table public.door_events to postgres, anon, authenticated, service_role;
grant usage, select on sequence public.door_events_id_seq to postgres, anon, authenticated, service_role;
create index if not exists door_events_door_time on public.door_events (door_id, received_at desc);

-- =========================================================================
-- door_commands: remote pulse / mode / power_cycle queue (SENSITIVE)
-- =========================================================================
create table if not exists public.door_commands (
  id            uuid primary key default gen_random_uuid(),
  door_id       text not null references public.doors(id) on delete cascade,
  cmd           text not null check (cmd in ('pulse','mode','power_cycle')),
  value         text,
  created_at    timestamptz not null default now(),
  delivered_at  timestamptz
);
grant all on table public.door_commands to postgres, anon, authenticated, service_role;
create index if not exists door_commands_pending on public.door_commands (door_id) where delivered_at is null;

-- =========================================================================
-- card_version bump: any change to a door's cards makes it re-download its list
-- =========================================================================
create or replace function public.bump_card_version() returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.doors set card_version = card_version + 1
  where id in (coalesce(new.door_id, old.door_id), coalesce(old.door_id, new.door_id));
  return null;
end $$;
revoke all on function public.bump_card_version() from public, anon, authenticated;

drop trigger if exists trg_bump_card_version on public.door_credentials;
create trigger trg_bump_card_version
after insert or update or delete on public.door_credentials
for each row execute function public.bump_card_version();

-- =========================================================================
-- RLS: on everywhere, service_role only. anon/authenticated get nothing
-- (the GRANTs above are the API-access layer; these policies are the gate).
-- Add org/property-scoped policies for Nexus admin screens in a later migration.
-- =========================================================================
alter table public.doors            enable row level security;
alter table public.door_credentials enable row level security;
alter table public.door_events      enable row level security;
alter table public.door_commands    enable row level security;

drop policy if exists "service_role all doors" on public.doors;
create policy "service_role all doors" on public.doors
  for all to service_role using (true) with check (true);

drop policy if exists "service_role all door_credentials" on public.door_credentials;
create policy "service_role all door_credentials" on public.door_credentials
  for all to service_role using (true) with check (true);

drop policy if exists "service_role all door_events" on public.door_events;
create policy "service_role all door_events" on public.door_events
  for all to service_role using (true) with check (true);

drop policy if exists "service_role all door_commands" on public.door_commands;
create policy "service_role all door_commands" on public.door_commands
  for all to service_role using (true) with check (true);

commit;

